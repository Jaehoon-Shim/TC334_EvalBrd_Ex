/* =========================================================
 * NN calculation
 * ========================================================= */
void NN_Run(volatile float *x)
{
    uint32 i;
    uint32 j;
    uint32 best_index;
    float max_logit;
    float probability_sum;

    /* 1. Copy inputs and apply the checkpoint StandardScaler. */
    START_TICK_MANAGER(NN_Time1);
    for (i = 0U; i < NN_INPUT_NUM; i++) {
        nn_input[i] = x[i];
        nn_input_normalized[i] =
            (nn_input[i] - nn_x_mean[i]) / nn_x_scale[i];
    }
    END_TICK_MANAGER(NN_Time1);

    /* 2. Hidden layer 1 + ReLU */
    START_TICK_MANAGER(NN_Time2);
    for (j = 0U; j < HIDDEN1_NUM; j++) {
        hidden_output1[j] = nn_bias1[j];
        for (i = 0U; i < NN_INPUT_NUM; i++) {
            hidden_output1[j] +=
                nn_input_normalized[i] * nn_theta1[i][j];
        }
        if (hidden_output1[j] < 0.0f) {
            hidden_output1[j] = 0.0f;
        }
    }
    END_TICK_MANAGER(NN_Time2);

    /* 3. Hidden layer 2 + ReLU */
    START_TICK_MANAGER(NN_Time3);
    for (j = 0U; j < HIDDEN2_NUM; j++) {
        hidden_output2[j] = nn_bias2[j];
        for (i = 0U; i < HIDDEN1_NUM; i++) {
            hidden_output2[j] += hidden_output1[i] * nn_theta2[i][j];
        }
        if (hidden_output2[j] < 0.0f) {
            hidden_output2[j] = 0.0f;
        }
    }
    END_TICK_MANAGER(NN_Time3);

    /* 4. Seven output logits (no activation). */
    START_TICK_MANAGER(NN_Time4);
    for (j = 0U; j < NN_OUTPUT_NUM; j++) {
        nn_logits[j] = nn_bias3[j];
        for (i = 0U; i < HIDDEN2_NUM; i++) {
            nn_logits[j] += hidden_output2[i] * nn_theta3[i][j];
        }
    }
    END_TICK_MANAGER(NN_Time4);



    /* 5. Stable softmax, argmax, Fault ID mapping, and confidence. */
    START_TICK_MANAGER(NN_Time5);
    best_index = 0U;
    max_logit = nn_logits[0U];
    for (i = 1U; i < NN_OUTPUT_NUM; i++) {
        if (nn_logits[i] > max_logit) {
            max_logit = nn_logits[i];
            best_index = i;
        }
    }

    probability_sum = 0.0f;
    for (i = 0U; i < NN_OUTPUT_NUM; i++) {
        nn_probabilities[i] = expf(nn_logits[i] - max_logit);
        probability_sum += nn_probabilities[i];
    }

    for (i = 0U; i < NN_OUTPUT_NUM; i++) {
        nn_probabilities[i] /= probability_sum;
    }

    Fault_ID = nn_class_ids[best_index];
    Fault_Confidence = nn_probabilities[best_index];

    END_TICK_MANAGER(NN_Time5);

}
